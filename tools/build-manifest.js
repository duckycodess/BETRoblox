"use strict"

// Prepares the unpacked extension for a browser to load.
//
// Chromium wants a file named manifest.json; this tree keeps one manifest per
// target instead, so the loadable file is generated. It is gitignored, and a
// gitignored sidecar records where it came from so a rerun can tell its own
// output from a manifest someone wrote by hand.
//
// The build is idempotent: running it twice writes once. It never writes when
// validation fails, and never overwrites a manifest it did not generate unless
// --force says to.
//
// Usage:
//   node tools/build-manifest.js                  # chrome, into the repo root
//   node tools/build-manifest.js --target=firefox
//   node tools/build-manifest.js --check          # validate only, write nothing
//   node tools/build-manifest.js --out=/tmp/ext   # write into a copy of the tree
//
// --out expects a directory that already holds the extension's files: the
// generated manifest is validated against the directory a browser would load,
// so a bare empty directory will (correctly) fail that check.
//   node tools/build-manifest.js --force          # overwrite a foreign manifest.json

const fs = require("node:fs")
const path = require("node:path")
const crypto = require("node:crypto")
const { execFileSync } = require("node:child_process")

const REPO = path.resolve(__dirname, "..")
const SIDECAR = ".manifest-build.json"
const TARGETS = ["chrome", "firefox"]

const arg = name => {
	const hit = process.argv.find(a => a === `--${name}` || a.startsWith(`--${name}=`))
	if(!hit) { return null }
	return hit.includes("=") ? hit.slice(hit.indexOf("=") + 1) : true
}

const target = arg("target") || "chrome"
const checkOnly = arg("check") === true
const force = arg("force") === true
const outDir = path.resolve(arg("out") || REPO)

if(!TARGETS.includes(target)) {
	console.error(`Unknown --target "${target}". Expected one of: ${TARGETS.join(", ")}`)
	process.exit(2)
}

const sourcePath = path.join(REPO, `manifest.${target}.json`)

if(!fs.existsSync(sourcePath)) {
	console.error(`Source manifest not found: ${sourcePath}`)
	process.exit(2)
}

// Nothing is written unless the checked-in manifests and asset registries are
// already consistent.
try {
	execFileSync(process.execPath, [path.join(__dirname, "validate-extension.js")], { stdio: "inherit" })
} catch {
	console.error("Refusing to build: source validation failed.")
	process.exit(1)
}

if(checkOnly) {
	console.log("--check: validation only, nothing written.")
	process.exit(0)
}

const sha256 = buffer => crypto.createHash("sha256").update(buffer).digest("hex")

const sourceBytes = fs.readFileSync(sourcePath)
const sourceHash = sha256(sourceBytes)

const generatedPath = path.join(outDir, "manifest.json")
const sidecarPath = path.join(outDir, SIDECAR)

const readSidecar = () => {
	if(!fs.existsSync(sidecarPath)) { return null }
	try { return JSON.parse(fs.readFileSync(sidecarPath, "utf8")) }
	catch { return null }
}

const sidecar = readSidecar()
const existing = fs.existsSync(generatedPath) ? fs.readFileSync(generatedPath) : null

// A manifest.json we did not write is the user's. Overwriting it silently would
// destroy work; say so and make them ask.
if(existing && !force) {
	const ours = sidecar && sidecar.generatedSha256 === sha256(existing)

	if(!ours) {
		console.error([
			`Refusing to overwrite ${generatedPath}.`,
			sidecar
				? `  ${SIDECAR} does not match the file on disk, so it was edited or written by something else.`
				: `  There is no ${SIDECAR}, so this manifest was not generated by this tool.`,
			"  Re-run with --force to replace it, or move it aside first."
		].join("\n"))
		process.exit(3)
	}
}

if(existing && existing.equals(sourceBytes) && sidecar?.sourceSha256 === sourceHash && sidecar?.target === target) {
	console.log(`Already up to date: ${generatedPath} (target=${target}); nothing written.`)
} else {
	fs.mkdirSync(outDir, { recursive: true })

	// Write via a temp file so an interrupted run cannot leave a half manifest
	// that a browser would then try to load.
	const writeAtomic = (dest, data) => {
		const tmp = `${dest}.tmp-${process.pid}`
		fs.writeFileSync(tmp, data)
		fs.renameSync(tmp, dest)
	}

	writeAtomic(generatedPath, sourceBytes)
	writeAtomic(sidecarPath, `${JSON.stringify({
		target,
		source: `manifest.${target}.json`,
		sourceSha256: sourceHash,
		generatedSha256: sourceHash,
		generatedBy: "tools/build-manifest.js"
	}, null, "\t")}\n`)

	console.log(`Wrote ${generatedPath} from manifest.${target}.json`)
}

try {
	execFileSync(process.execPath, [
		path.join(__dirname, "validate-extension.js"),
		`--generated=${outDir}`,
		`--target=${target}`
	], { stdio: "inherit" })
} catch {
	console.error("Generated manifest failed validation.")
	process.exit(1)
}

if(outDir === REPO) {
	console.log([
		"",
		"Load it in Chromium:",
		"  1. Open chrome://extensions",
		"  2. Enable Developer mode",
		"  3. Choose \"Load unpacked\" and select:",
		`     ${REPO}`,
		"",
		"After changing extension code, press the reload icon on the BETRoblox card,",
		"then reload the Roblox tab. Requires Chromium 111 or newer."
	].join("\n"))
}
